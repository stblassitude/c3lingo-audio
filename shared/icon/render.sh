#!/bin/sh
# Renders the app icons and the launch/splash logo from c3lingo-logo.svg, which is a copy
# of c3lingo-logo.svg from https://codeberg.org/c3lingo/c3lingo-design.
#
# Needs rsvg-convert and ImageMagick 7 (brew install librsvg imagemagick).
# Writes the PNGs for the Apple app (the asset catalogs' Contents.json files are kept in
# git), the vector drawables for the Android app, and Google Play's icon and feature
# graphic.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
svg=$here/c3lingo-logo.svg
assets=$here/../../apple/c3lingo-audio/Assets.xcassets
android_res=$here/../../android/app/src/main/res
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Leave out timestamps, so unchanged icons render to identical files.
png() { magick "$@" -define png:exclude-chunks=date,time,tIME "PNG32:$out"; }

# round <in> <size> <radius>: clip a square image to a rounded rectangle
round() {
    magick "$1" \( -size "$2x$2" xc:black -fill white \
        -draw "roundrectangle 0,0,$(($2 - 1)),$(($2 - 1)),$3,$3" \) \
        -alpha off -compose CopyOpacity -composite "$tmp/rounded.png"
}

# iOS: full-bleed square, the system applies the mask
rsvg-convert -w 1024 -h 1024 "$svg" -o "$tmp/ios.png"
out=$assets/AppIcon.appiconset/AppIcon-1024.png
magick "$tmp/ios.png" -alpha off -define png:exclude-chunks=date,time,tIME "PNG24:$out"

# macOS: 824pt rounded rectangle with a soft shadow on a 1024 canvas (Apple's icon grid)
rsvg-convert -w 824 -h 824 "$svg" -o "$tmp/mac-tile.png"
round "$tmp/mac-tile.png" 824 185
magick "$tmp/rounded.png" \( +clone -background black -shadow 30x10+0+12 \) +swap \
    -background none -layers merge +repage "$tmp/shadowed.png"
magick -size 1024x1024 xc:none "$tmp/shadowed.png" -gravity center -geometry +0-4 \
    -composite "$tmp/mac-1024.png"
for size in 16 32 64 128 256 512 1024; do
    out=$assets/AppIcon.appiconset/AppIcon-mac-$size.png
    png "$tmp/mac-1024.png" -resize "${size}x$size"
done

# visionOS: yellow back layer, glyphs in front, scaled to 75% to fit the circular mask
stack=$assets/AppIcon-visionOS.solidimagestack
sed -e 's|<rect class="cls-1" width="513" height="513"/>|<g transform="translate(256 256) scale(0.75) translate(-256 -256)">|' \
    -e 's|</svg>|</g></svg>|' "$svg" > "$tmp/vision-front.svg"
rsvg-convert -w 1024 -h 1024 "$tmp/vision-front.svg" -o "$tmp/vision-front.png"
out=$stack/Front.solidimagestacklayer/Content.imageset/Front.png
png "$tmp/vision-front.png"
out=$stack/Back.solidimagestacklayer/Content.imageset/Back.png
magick -size 1024x1024 xc:'#fff200' -alpha off -define png:exclude-chunks=date,time,tIME "PNG24:$out"

# Google Play: full-bleed square like iOS, Play applies the mask; and the feature graphic,
# the glyphs on the yellow background, small enough to survive Play's cropping
play=$here/../../android/fastlane/metadata/android/en-US/images
mkdir -p "$play"
rsvg-convert -w 512 -h 512 "$svg" -o "$tmp/play-icon.png"
out=$play/icon.png
png "$tmp/play-icon.png"
rsvg-convert -w 560 -h 560 "$tmp/vision-front.svg" -o "$tmp/feature-glyphs.png"
out=$play/featureGraphic.png
magick -size 1024x500 xc:'#fff200' "$tmp/feature-glyphs.png" -gravity center -composite \
    -alpha off -define png:exclude-chunks=date,time,tIME "PNG24:$out"

# Launch and splash screen logo: 128pt rounded tile, corner radius as on the iOS icon
for scale in 1 2 3; do
    size=$((128 * scale))
    rsvg-convert -w "$size" -h "$size" "$svg" -o "$tmp/logo.png"
    round "$tmp/logo.png" "$size" $((115 * size / 512))
    out=$assets/Logo.imageset/Logo@${scale}x.png
    png "$tmp/rounded.png"
done

# Now Playing and media session artwork for the lock screen, Control Center and the
# watch: full-bleed square like an album cover, the system rounds the corners
rsvg-convert -w 512 -h 512 "$svg" -o "$tmp/artwork.png"
for out in "$assets/Artwork.imageset/Artwork.png" "$android_res/raw/artwork.png"; do
    magick "$tmp/artwork.png" -alpha off -define png:exclude-chunks=date,time,tIME "PNG24:$out"
done

# Android: vector drawables built from the SVG's paths
paths() {
    grep -o ' d="[^"]*"' "$svg" | sed -e 's| d="|        <path android:fillColor="#000000" android:pathData="|' -e 's|$| />|'
}

# Adaptive icon foreground and monochrome layer. Scaled like the visionOS front layer, but
# into the 66dp safe zone of the 108dp canvas.
{
    cat <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by shared/icon/render.sh, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="512"
    android:viewportHeight="512">
    <group
        android:pivotX="256"
        android:pivotY="256"
        android:scaleX="0.458"
        android:scaleY="0.458">
XML
    paths
    cat <<XML
    </group>
</vector>
XML
} > "$android_res/drawable/ic_launcher_foreground.xml"

# Splash screen logo: 128dp rounded tile, as on the Apple splash screen
{
    cat <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by shared/icon/render.sh, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="128dp"
    android:height="128dp"
    android:viewportWidth="512"
    android:viewportHeight="512">
    <path
        android:fillColor="#FFF200"
        android:pathData="M115,0H397A115,115 0,0 1,512,115V397A115,115 0,0 1,397,512H115A115,115 0,0 1,0,397V115A115,115 0,0 1,115,0Z" />
XML
    paths | sed 's|^    ||'
    echo "</vector>"
} > "$android_res/drawable/logo.xml"

# Launcher icons for Android 7, which has no adaptive icons: the rounded tile, and a
# circle for launchers that use round icons, both 48dp with a 2dp margin
for density in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
    name=${density%:*}
    size=$(echo "${density#*:} * 48 / 1" | bc)
    inner=$(echo "${density#*:} * 44 / 1" | bc)
    mkdir -p "$android_res/mipmap-$name"
    rsvg-convert -w "$inner" -h "$inner" "$svg" -o "$tmp/legacy.png"
    round "$tmp/legacy.png" "$inner" $((115 * inner / 512))
    out=$android_res/mipmap-$name/ic_launcher.png
    png "$tmp/rounded.png" -background none -gravity center -extent "${size}x$size"
    rsvg-convert -w "$inner" -h "$inner" "$tmp/vision-front.svg" -o "$tmp/glyphs.png"
    magick -size "${inner}x$inner" xc:none -fill '#fff200' \
        -draw "circle $((inner / 2)),$((inner / 2)) $((inner / 2)),0" "$tmp/glyphs.png" -composite "$tmp/circle.png"
    out=$android_res/mipmap-$name/ic_launcher_round.png
    png "$tmp/circle.png" -background none -gravity center -extent "${size}x$size"
done
